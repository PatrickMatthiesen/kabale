import { mkdir, readdir, readFile, writeFile, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Use Bun's portable backend so CI and Windows generate identical content hashes.
Bun.Image.backend = 'bun';
const directory = 'assets/cards/optimized';
const sourceDirectory = 'assets/cards/layered';
await mkdir(directory, { recursive: true });
const manifest = {};
const generatedFiles = new Set();
const expectedSources = ['engraved', 'woodcut'].flatMap(style =>
  ['clubs', 'spades', 'hearts', 'diamonds'].flatMap(suit => ['numbers', 'court'].map(kind => `${style}-${suit}-${kind}.jpg`))
);
const sourceNames = (await readdir(sourceDirectory)).filter(name => name.endsWith('.jpg')).sort();
const missingSources = expectedSources.filter(name => !sourceNames.includes(name));
if (missingSources.length) throw new Error(`Missing layered card artwork: ${missingSources.join(', ')}`);
for (const name of sourceNames) {
  const key = name.slice(0,-4);
  const input = `${sourceDirectory}/${name}`;
  const columns = key.endsWith('-court') ? 3 : 1;
  const metadata = await Bun.file(input).image().metadata();
  manifest[key] = [];
  for (const [tier, width] of [['small',columns*80],['medium',columns*160],['full',metadata.width]]) {
    const outputWidth = Math.min(width,metadata.width);
    const bytes = await Bun.file(input).image().resize(outputWidth).webp({quality:82}).bytes();
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0,16);
    const file = `${key}-${tier}.${hash}.webp`;
    await Bun.write(`${directory}/${file}`,bytes);
    generatedFiles.add(file);
    manifest[key].push({url:`./${directory}/${file}`,width:outputWidth/columns,bytes:bytes.length});
  }
}
await writeFile('src/art-manifest.js', `// Generated by bun run prepare:images. Image bytes determine each URL.\nexport const artManifest = ${JSON.stringify(manifest,null,2)};\n`);
// Remove superseded generated variants only after all replacements are ready.
const generatedName = /^(engraved|woodcut)-(clubs|spades|hearts|diamonds)-(court|numbers)-(small|medium|full)\.[a-f0-9]{16}\.webp$/;
const retained = JSON.parse(await readFile('assets/cards/retained-art.json', 'utf8'));
if (typeof retained.reason !== 'string' || !retained.reason.trim() || !Array.isArray(retained.files)) {
  throw new Error('assets/cards/retained-art.json must include a reason and files array');
}
const retainedFiles = new Set(retained.files);
if (retainedFiles.size !== retained.files.length || retained.files.some(file => typeof file !== 'string' || !generatedName.test(file))) {
  throw new Error('Retained artwork list contains a duplicate or invalid filename');
}
const existingFiles = new Set(await readdir(directory));
const missingRetainedFiles = retained.files.filter(file => !existingFiles.has(file));
if (missingRetainedFiles.length) throw new Error(`Missing retained card artwork: ${missingRetainedFiles.join(', ')}`);
for (const file of existingFiles) {
  if (generatedName.test(file) && !generatedFiles.has(file) && !retainedFiles.has(file)) await unlink(`${directory}/${file}`);
}
console.log(`Prepared ${Object.keys(manifest).length} sheets in three resolutions.`);
