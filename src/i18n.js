const languages = ['en', 'da'];
const languageKey = 'kabale-language';

export function translate(language, text, values) {
  const translated = language === 'da' && Object.hasOwn(danish, text) ? danish[text] : text;
  return values ? translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match) : translated;
}

export function loadLanguage(storage, browserLanguages = []) {
  try {
    const saved = storage?.getItem(languageKey);
    if (languages.includes(saved)) return saved;
  } catch { /* Browser preferences still work if storage is blocked. */ }
  return browserLanguages.map(locale => locale.toLowerCase().split('-')[0]).find(locale => languages.includes(locale)) ?? 'en';
}

export function saveLanguage(storage, language) {
  const selected = languages.includes(language) ? language : 'en';
  try { storage?.setItem(languageKey, selected); } catch { /* The current tab can still use this language. */ }
  return selected;
}

/** Capture the English labels once so changing language never translates a translation. */
export function bindDocumentLanguage(document) {
  const title = document.title;
  const text = [...document.querySelectorAll('[data-i18n]')].map(node => [node, node.textContent]);
  const attributes = ['aria-label','title'].flatMap(attribute =>
    [...document.querySelectorAll(`[data-i18n-${attribute}]`)]
      .map(node => [node, attribute, node.getAttribute(attribute)])
  );
  return language => {
    document.documentElement.lang = language;
    document.title = translate(language,title);
    for (const [node, label] of text) node.textContent = translate(language,label);
    for (const [node, attribute, label] of attributes) node.setAttribute(attribute,translate(language,label));
  };
}
